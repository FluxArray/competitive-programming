const int MAX_N = 1000;
bool lit[MAX_N][MAX_N];  // the grid itself
int row_num;
int col_num;
bool visited[MAX_N][MAX_N];  // keeps track of which nodes have been visited
int curr_size = 0;           // reset to 0 each time we start a new component

map <pair<int, int>, vector<pair<int, int>>> adj;
int dr[] = {-1, 1, 0, 0};
int dc[] = {0, 0, -1, 1};

void floodfill(int r, int c) {
    if (r < 0 || r >= row_num || c < 0 || c >= col_num) return;
    if (visited[r][c]) return;
    visited[r][c] = true;
    for (pair<int, int> i : adj[{r, c}]) {
        int nx = i.fi;
        int ny = i.se;
        
        if (!lit[nx][ny]) {
            lit[nx][ny] = true;

            bool reach = false;
            for (int i = 0; i < 4; i++) {
                int adjr = nx + dr[i];
                int adjc = ny + dc[i];
                if (adjr >= 0 && adjr < row_num && adjc >= 0 && adjc < col_num) {
                    if (visited[adjr][adjc]) {
                        reach = true;
                    }
                }
            }

            if (reach) {
                floodfill(nx, ny);
            }
        }
    }

    for (int i = 0; i < 4; i++) {
        int nr = r + dr[i];
        int nc = c + dc[i];
        
        if (nr >= 0 && nr < row_num && nc >= 0 && nc < col_num) {
            if (lit[nr][nc] && !visited[nr][nc]) {
                floodfill(nr, nc);
            }
        }
    }
}

