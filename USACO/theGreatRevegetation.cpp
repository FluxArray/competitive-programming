const int MAX_N = 200005;
int n, m;
int color[MAX_N]; 
vpi adj[MAX_N];
bool possible = true;

void dfs(int u, int c) {
    color[u] = c;
    trav(edge, adj[u]) {
        int v = edge.first;
        int rule = edge.second;
        int req = (rule == 0) ? c : (3 - c);
        
        if (color[v]) {
            if (color[v] != req) {
                possible = false;
            }
        } else {
            dfs(v, req);
        }
    }
}

