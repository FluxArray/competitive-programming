const int MAX_N = 4005;
bool grid[MAX_N][MAX_N];  // the grid itself
int row_num;
int col_num;
bool visited[MAX_N][MAX_N];  // keeps track of which nodes have been visited
int curr_size = 0;           // reset to 0 each time we start a new component
int dr[] = {-1, 1, 0, 0};
int dc[] = {0, 0, -1, 1};

void floodfill(int r, int c, int color) {
    queue<pair<int, int>> q;
    q.push({r, c});
    visited[r][c] = true;

    while (!q.empty()) {
        int r = q.front().fi;
        int c = q.front().se;
        q.pop();

        for (int i = 0; i < 4; i++) {
            int nr = r + dr[i];
            int nc = c + dc[i];

            if (nr >= 0 && nr < row_num && nc >= 0 && nc < col_num) {
                if (!visited[nr][nc] && grid[nr][nc] == color) {
                    visited[nr][nc] = true;
                    q.push({nr, nc});
                }
            }
        }
    }
}

