void solve() {
    freopen("rental.in", "r", stdin);
    freopen("rental.out", "w", stdout);
    
    ll n, m, r;
    cin >> n >> m >> r;

    vl c(n);
    vpi shops(m);
    vl rent(r);

    for (int i = 0; i < n; i++) cin >> c[i];
    for (int i = 0; i < m; i++) {
        cin >> shops[i].se >> shops[i].fi;
    }

    for (int i = 0; i < r; i++) {
        cin >> rent[i];
    }

    RSORT(c);
    RSORT(shops);
    RSORT(rent);

    vl prefmilk(n + 1);
    vl prefrent(n + 1);

    ll I = 0;
    for (int j = 1; j <= n; j++) {
        ll temp = 0;
        ll cc = c[j - 1];
        
        while (cc > 0 && I < m) {
            if (cc >= shops[I].se) {
                temp += shops[I].fi * shops[I].se;
                cc -= shops[I].se;
                shops[I].se = 0;
                I++;
            } else {
                temp += cc * shops[I].fi;
                shops[I].se -= cc;
                cc = 0;
            }
        }
        prefmilk[j] = prefmilk[j - 1] + temp; 
    }

    for (int i = 1; i <= n; i++) {
        prefrent[i] = prefrent[i - 1];
        if (i - 1 < r) {
            prefrent[i] += rent[i - 1]; 
        }
    }

    ll profit = 0;
    for (int i = 0; i <= n; i++) {
        profit = max(profit, prefmilk[i] + prefrent[n - i]);
    }
    
    cout << profit << '\n';
}

