ll exGCD(ll a, ll b, ll &x, ll &y) {
    if (b == 0) {
        x = 1; y = 0;
        return a;
    }
    ll x1, y1;
    ll d = exGCD(b, a % b, x1, y1);
    x = y1;
    y = x1 - y1 * (a / b);
    return d;
}
//main
pair<ll, ll> CRT(const vl& a, const vl& m) {
    if (a.empty()) return {0, 1};

    ll ans = a[0];
    ll lcm = m[0];

    for (int i = 1; i < SZ(a); i++) {
        ll x, y;
        ll d = exGCD(lcm, m[i], x, y);

        if ((a[i] - ans) % d != 0) return {-1, -1}; 

        ll curmod = m[i] / d;
        ll gap = (a[i] - ans) / d;
        ll k = (ll)(((i128)(x % curmod + curmod) % curmod) * ((i128)(gap % curmod + curmod) % curmod) % curmod);

        ans = ans + k * lcm;
        lcm = (lcm / d) * m[i]; 
        ans %= lcm;
    }

    return {ans, lcm};
}

void solve() {
    int a, n, b, m; cin >> a >> n >> b >> m;
    vl aah = {a, b};
    vl maah = {n, m};
    ll x = CRT(aah, maah).fi, y = CRT(aah, maah).se;
    if (x == -1 && y == -1) {
        cout << "no solution" << '\n';
        return;
    }
    
    cout << CRT(aah, maah).fi << ' ' << CRT(aah, maah).se << '\n';
}

