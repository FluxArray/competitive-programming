void solve() {
    ll n; cin >> n;
    vl hmm(n);

    for (int i = 0; i < n; i++) {
        cin >> hmm[i];
    }

    SORT(hmm);
    ll lol;
    if (n % 2 == 1) {
        lol = hmm[(n) / 2];
    } else {
        ll a = hmm[n / 2];
        ll b = hmm[(n - 1) / 2];
        lol = (a + b) / 2;
    }

    ll cost = 0;
    for (int i = 0; i < n; i++) {
        cost += abs(lol - hmm[i]);
    }

    cout << cost << '\n';
}

