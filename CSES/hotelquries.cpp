/**
 * Description: Segment Tree with Lazy Propagation.
 * Time: O(N) build, O(log N) per update/query.
 * Note: Uses O(4N) memory. Handles non-invertible operations.
 */

template<typename valueType, typename tagType>
class segmentTreeNode {
public:
    int id, left, right;
    valueType val;
    tagType tag;
};

template<typename valueType, typename tagType, valueType (*merge)(valueType, valueType), void (*update)(segmentTreeNode<valueType, tagType>&, tagType)>
class segmentTree {
private:
    vector<segmentTreeNode<valueType, tagType> > nodes;
    int leftRange, rightRange;
    valueType valueZero;
    tagType tagZero;

    void pushup(int cur) {
        nodes[cur].val = merge(nodes[cur << 1].val, nodes[cur << 1 | 1].val);
    }
    
    void pushdown(int cur) {
        update(nodes[cur << 1], nodes[cur].tag);
        update(nodes[cur << 1 | 1], nodes[cur].tag);
        nodes[cur].tag = tagZero;
    }
    
    void build(int cur, int l, int r, const vector<valueType>& initValue) {
        nodes[cur].id = cur;
        nodes[cur].left = l;
        nodes[cur].right = r;
        nodes[cur].tag = tagZero;
        if (l == r - 1) nodes[cur].val = initValue[l - leftRange];
        else
        {
            build(cur << 1, l, (l + r) >> 1, initValue);
            build(cur << 1 | 1, (l + r) >> 1, r, initValue);
            pushup(cur);
        }
    }
    
    void init(const vector<valueType>& _initValue,
              const valueType& _valueZero,
              const tagType& _tagZero) {
        valueZero = _valueZero;
        tagZero = _tagZero;
        nodes.resize((rightRange - leftRange) << 2);
        build(1, leftRange, rightRange, _initValue);
    }
    
    void modify(int cur, int l, int r, int L, int R, const tagType& tag) {
        if (l >= R || r <= L) return;
        if (L <= l && r <= R) update(nodes[cur], tag);
        else {
            pushdown(cur);
            modify(cur << 1, l, (l + r) >> 1, L, R, tag);
            modify(cur << 1 | 1, (l + r) >> 1, r, L, R, tag);
            pushup(cur);
        }
    }
    
    valueType query(int cur, int l, int r, int L, int R) {
        if (l >= R || r <= L) return valueZero;
        if (L <= l && r <= R) return nodes[cur].val;
        pushdown(cur);
        return merge(query(cur << 1, l, (l + r) >> 1, L, R),
                     query(cur << 1 | 1, (l + r) >> 1, r, L, R));
    }

    template<typename F>
    int find_first(int cur, int l, int r, F check) {
        if (l == r - 1) return l;
        pushdown(cur);
        int mid = (l + r) >> 1;
        if (check(nodes[cur << 1].val)) {
            return find_first(cur << 1, l, mid, check);
        } else {
            return find_first(cur << 1 | 1, mid, r, check);
        }
    }
    
public:
    segmentTree() {}
    segmentTree(int _leftRange, int _rightRange, const vector<valueType>& _initValue, const valueType& _valueZero, const tagType& _tagZero) {
        leftRange = _leftRange;
        rightRange = _rightRange;
        init(_initValue, _valueZero, _tagZero);
    }
    
    segmentTree(int size, const vector<valueType>& _initValue, const valueType& _valueZero, const tagType& _tagZero) {
        leftRange = 1;
        rightRange = size + 1;
        init(_initValue, _valueZero, _tagZero);
    }
    
    void modify(int l, int r, const tagType& tag) {
        modify(1, leftRange, rightRange, l, r, tag);
    }
    
    void modify(int p, const tagType& tag) {
        modify(p, p + 1, tag);
    }
    
    valueType query(int l, int r) {
        return query(1, leftRange, rightRange, l, r);
    }
    
    valueType query(int p) {
        return query(p, p + 1);
    }
    template<typename F>
    int find_first(F check) {
        return find_first(1, leftRange, rightRange, check);
    }
};

struct Node { int val; }; //node
struct Tag { int tag; }; //lazy
Node merge(Node a, Node b) {
    Node res;
    res.val = max(a.val, b.val);
    return res;
}

void update(segmentTreeNode<Node, Tag>& node, Tag tag) {
    if (tag.tag != -1) {
        node.val.val = tag.tag;
        node.tag = tag;
    }
}

void solve() {
    int n, m; cin >> n >> m;
    vector<Node> h(n);
    vi r(m);
    for (int i = 0; i < n; i++) { cin >> h[i].val; }
    for (int j = 0; j < m; j++) { cin >> r[j]; }
    Node valueZero = {0};
    Tag tagZero = {-1};

    segmentTree<Node, Tag, merge, update> segs(n, h, valueZero, tagZero);
    for (int i = 0; i < m; i++) {
        if (segs.query(1, n + 1).val < r[i]) {
            cout << 0 << ' ';
        } else {
            int idx = segs.find_first([&](Node left) { return left.val >= r[i]; });
            cout << idx << ' ';
            int temp = segs.query(idx).val;
            segs.modify(idx, {temp - r[i]});
        }
    }
    cout << '\n';
}

