#pragma once

template<int MOD, int RT> struct mint {
    static const int mod = MOD;
    static constexpr mint rt() { return RT; } // primitive root for FFT
    int v; explicit operator int() const { return v; } // explicit -> don't silently convert to int
    mint():v(0) {}
    mint(ll _v) { v = int((-MOD < _v && _v < MOD) ? _v : _v % MOD);
        if (v < 0) v += MOD; }
    bool operator==(const mint& o) const {
        return v == o.v; }
    friend bool operator!=(const mint& a, const mint& b) { 
        return !(a == b); }
    friend bool operator<(const mint& a, const mint& b) { 
        return a.v < b.v; }
    friend istream& operator>>(istream& is, mint& a) {
        ll x;is >> x;a = mint(x);return is; }
    friend string to_string(const mint& a) { return to_string(a.v); }
   
    mint& operator+=(const mint& o) { 
        if ((v += o.v) >= MOD) v -= MOD; 
        return *this; }
    mint& operator-=(const mint& o) { 
        if ((v -= o.v) < 0) v += MOD; 
        return *this; }
    mint& operator*=(const mint& o) { 
        v = int((ll)v*o.v%MOD); return *this; }
    mint& operator/=(const mint& o) { return (*this) *= inv(o); }
    friend mint pow(mint a, ll p) {
        mint ans = 1; assert(p >= 0);
        for (; p; p /= 2, a *= a) if (p&1) ans *= a;
        return ans; }
    friend mint inv(const mint& a) { assert(a.v != 0); 
        return pow(a,MOD-2); }
        
    mint operator-() const { return mint(-v); }
    mint& operator++() { return *this += 1; }
    mint& operator--() { return *this -= 1; }
    friend mint operator+(mint a, const mint& b) { return a += b; }
    friend mint operator-(mint a, const mint& b) { return a -= b; }
    friend mint operator*(mint a, const mint& b) { return a *= b; }
    friend mint operator/(mint a, const mint& b) { return a /= b; }
};

using mi = mint<MOD,5>; // 5 is primitive root for both common mods
using vmi = vector<mi>;
using pmi = pair<mi,mi>;
using vpmi = vector<pmi>;

vector<vmi> scmb; // small combinations
void genComb(int SZ) {
    scmb.assign(SZ, vmi(SZ, 0)); scmb[0][0] = 1;
    for (int i = 1; i < SZ; ++i) {
        for (int j = 0; j <= i; ++j) {
            // Pascal's Triangle addition
            scmb[i][j] = scmb[i-1][j] + (j > 0 ? scmb[i-1][j-1] : 0);
        }
    }
}

void solve() {
    int n; cin >> n;
    mi num = 1, sum = 1, prod = 1;
    ll nummod = 1;
    for (int i = 0; i < n; i++) {
        mi x;
        ll k;
        cin >> x >> k;
        num *= (k + 1);
        mi hmm = (pow(x, k + 1) - 1) / (x - 1);
        sum *= hmm;

        ll exp = (k * (k + 1) / 2) % (MOD - 1);
        ll totalexp = (nummod * exp) % (MOD - 1);

        prod = pow(prod, k + 1) * pow(x, totalexp);
        nummod = (nummod * (k + 1)) % (MOD - 1);
    }
    cout << num.v << ' ' << sum.v << ' ' << prod.v << '\n';
}

